/// Hashcash Proof-of-Work stamp verifying that computational work was completed by the sender.
///
/// Used to deter Sybil identity rotation and unsolicited message bombing on open LANs.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct HashcashStamp {
    /// Required difficulty in leading zero bits.
    pub bits: u32,

    /// Canonical uppercase SHA-256 fingerprint of the sender.
    pub sender_fp: String,

    /// Canonical uppercase SHA-256 fingerprint of the recipient target.
    pub target_fp: String,

    /// Time bucket value (UNIX timestamp divided by bucket interval).
    pub time_bucket: u64,

    /// Nonce satisfying the leading-zero-bit proof condition.
    pub nonce: u64,
}

impl HashcashStamp {
    /// Creates a new `HashcashStamp`.
    pub fn new(
        bits: u32,
        sender_fp: impl Into<String>,
        target_fp: impl Into<String>,
        time_bucket: u64,
        nonce: u64,
    ) -> Self {
        Self {
            bits,
            sender_fp: sender_fp.into(),
            target_fp: target_fp.into(),
            time_bucket,
            nonce,
        }
    }

    /// Constructs the canonical payload bytes used for Hashcash SHA-256 calculation:
    /// `SENDER_FP:TARGET_FP:TIME_BUCKET:NONCE`
    pub fn canonical_payload(sender_fp: &str, target_fp: &str, time_bucket: u64, nonce: u64) -> Vec<u8> {
        format!(
            "{}:{}:{}:{}",
            sender_fp.to_ascii_uppercase(),
            target_fp.to_ascii_uppercase(),
            time_bucket,
            nonce
        )
        .into_bytes()
    }

    /// Returns the canonical payload bytes for this stamp instance.
    pub fn canonical_bytes(&self) -> Vec<u8> {
        Self::canonical_payload(&self.sender_fp, &self.target_fp, self.time_bucket, self.nonce)
    }
}

/// Trust handshake request sent by a Stranger to introduce themselves and request contact approval.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TrustRequestDto {
    /// Unique identifier for this trust request.
    pub request_id: String,

    /// Canonical uppercase SHA-256 fingerprint of the sender.
    pub sender_fp: String,

    /// Human-readable device/user alias of the sender.
    pub sender_alias: String,

    /// Canonical uppercase SHA-256 fingerprint of the target recipient.
    pub target_fp: String,

    /// Plain UTF-8 introduction message (max 280 characters, no media).
    pub message: String,

    /// Hashcash Proof-of-Work stamp satisfying recipient difficulty.
    pub pow_stamp: HashcashStamp,

    /// Timestamp in milliseconds when the request was generated.
    pub timestamp_ms: u64,

    /// Optional digital signature over canonical request bytes.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub signature: Option<String>,
}

impl TrustRequestDto {
    /// Canonical bytes for trust request signature calculation and verification.
    pub fn canonical_signing_bytes(&self) -> Vec<u8> {
        format!(
            "{}:{}:{}:{}:{}:{}",
            self.request_id,
            self.sender_fp.to_ascii_uppercase(),
            self.sender_alias,
            self.target_fp.to_ascii_uppercase(),
            self.message,
            self.timestamp_ms
        )
        .into_bytes()
    }
}

/// Resumable transfer state DTO exchanged when resuming an interrupted media or file transfer.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ResumeTransferDto {
    /// Session identifier of the interrupted transfer.
    pub session_id: String,

    /// File identifier within the session.
    pub file_id: String,

    /// Fingerprint of the sender.
    pub sender_fp: String,

    /// Fingerprint of the recipient.
    pub recipient_fp: String,

    /// Total promised byte length of the file.
    pub total_bytes: u64,

    /// Number of verified bytes already received on disk.
    pub received_bytes: u64,

    /// Expected SHA-256 checksum of the completed full file.
    pub sha256: String,

    /// Chunk size used for streaming (e.g. 131,072 bytes).
    pub chunk_size: usize,
}

