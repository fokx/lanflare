/// Rich chat content variants supported across LanFlare chat.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "camelCase")]
pub enum ChatContentDto {
    /// Plain UTF-8 text message.
    Text {
        text: String,
    },
    /// Image attachment with metadata and optional thumbnail preview.
    Image {
        file_name: String,
        size_bytes: u64,
        mime_type: String,
        sha256: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        thumbnail_base64: Option<String>,
    },
    /// Generic binary file attachment.
    File {
        file_name: String,
        size_bytes: u64,
        mime_type: String,
        sha256: String,
    },
    /// Audio / voice note recording.
    Voice {
        duration_ms: u32,
        size_bytes: u64,
        mime_type: String,
        sha256: String,
    },
    /// Video clip attachment with duration and optional thumbnail preview.
    Video {
        file_name: String,
        duration_ms: u32,
        size_bytes: u64,
        mime_type: String,
        sha256: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        thumbnail_base64: Option<String>,
    },
}

impl ChatContentDto {
    /// Returns true if this content variant is a rich media attachment (Image, File, Voice, or Video).
    pub fn is_media(&self) -> bool {
        !matches!(self, ChatContentDto::Text { .. })
    }

    /// Returns the text content if this is a plain text message.
    pub fn text_content(&self) -> Option<&str> {
        match self {
            ChatContentDto::Text { text } => Some(text.as_str()),
            _ => None,
        }
    }

    /// Returns the file name if this content has an associated file.
    pub fn file_name(&self) -> Option<&str> {
        match self {
            ChatContentDto::Image { file_name, .. }
            | ChatContentDto::File { file_name, .. }
            | ChatContentDto::Video { file_name, .. } => Some(file_name.as_str()),
            _ => None,
        }
    }

    /// Returns the byte size of this message content.
    pub fn size_bytes(&self) -> u64 {
        match self {
            ChatContentDto::Text { text } => text.len() as u64,
            ChatContentDto::Image { size_bytes, .. }
            | ChatContentDto::File { size_bytes, .. }
            | ChatContentDto::Voice { size_bytes, .. }
            | ChatContentDto::Video { size_bytes, .. } => *size_bytes,
        }
    }

    /// Returns the SHA-256 digest of the attachment if present.
    pub fn sha256(&self) -> Option<&str> {
        match self {
            ChatContentDto::Image { sha256, .. }
            | ChatContentDto::File { sha256, .. }
            | ChatContentDto::Voice { sha256, .. }
            | ChatContentDto::Video { sha256, .. } => Some(sha256.as_str()),
            ChatContentDto::Text { .. } => None,
        }
    }
}

/// Chat message wire DTO exchanged between peers or across mesh relays.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ChatMessageDto {
    /// Unique identifier for this message (UUID v4).
    pub id: String,

    /// Unique conversation identifier (e.g., peer fingerprint or group UUID).
    pub conversation_id: String,

    /// Canonical 64-character uppercase SHA-256 fingerprint of the author.
    pub sender_fp: String,

    /// Canonical 64-character uppercase SHA-256 fingerprint of the recipient (or group ID).
    pub recipient_fp: String,

    /// UNIX timestamp in milliseconds when the message was authored.
    pub timestamp_ms: u64,

    /// Message content payload.
    pub content: ChatContentDto,

    /// Optional reference to a parent message ID being replied to.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reply_to_id: Option<String>,

    /// Optional digital signature generated by the sender over canonical signing bytes.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub signature: Option<String>,
}

impl ChatMessageDto {
    /// Canonical signing bytes binding message ID, conversation, sender, recipient, timestamp, and reply.
    pub fn canonical_signing_bytes(&self) -> Vec<u8> {
        format!(
            "{}:{}:{}:{}:{}:{}",
            self.id,
            self.conversation_id,
            self.sender_fp.to_ascii_uppercase(),
            self.recipient_fp.to_ascii_uppercase(),
            self.timestamp_ms,
            self.reply_to_id.as_deref().unwrap_or("")
        )
        .into_bytes()
    }
}

